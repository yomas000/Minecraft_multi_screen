#!/usr/bin/env bash
# Assign controllers to players: each player presses a button on their pad in
# turn. Saved to controllers.conf by serial/MAC or USB port, so it survives
# reboots as long as wired pads stay in the same ports.
#   assign-controllers.sh [players]
set -euo pipefail

here=$(dirname "$(readlink -f "$0")")
# shellcheck source=sandbox-lib.sh
source "$here/sandbox-lib.sh"
if [[ -f "$SANDBOX_DIR/sandbox.conf" ]]; then
  # shellcheck source=/dev/null
  source "$SANDBOX_DIR/sandbox.conf"
fi
players="${1:-${PLAYERS:-4}}"

# Prints the first of the given event nodes to report a button press.
# input_event is 24 bytes on 64-bit (16 time, u16 type, u16 code, s32 value),
# so with -tu2 field 9 is the type (1 = EV_KEY) and field 11 the value (1 = down).
wait_for_button() {
  local tmp ev pid pids=()
  tmp=$(mktemp)
  for ev in "$@"; do
    (
      if stdbuf -i0 od -An -v -w24 -tu2 "/dev/input/$ev" 2>/dev/null |
         awk '$9 == 1 && $11 == 1 { found = 1; exit } END { exit !found }'; then
        echo "$ev" >>"$tmp"
      fi
    ) &
    pids+=("$!")
  done
  until [[ -s "$tmp" ]]; do sleep 0.1; done
  for pid in "${pids[@]}"; do
    pkill -P "$pid" 2>/dev/null || true
    kill "$pid" 2>/dev/null || true
  done
  head -n1 "$tmp"
  rm -f "$tmp"
}

mapfile -t pads < <(list_pads)
if [[ ${#pads[@]} -eq 0 ]]; then
  echo "No controllers found. Connect them (and close Steam if it's grabbing them), then retry." >&2
  exit 1
fi
for ev in "${pads[@]}"; do
  if [[ ! -r "/dev/input/$ev" ]]; then
    echo "Can't read /dev/input/$ev ($(pad_name "$ev")). Add yourself to the 'input' group or log in at the local seat." >&2
    exit 1
  fi
done

echo "Found ${#pads[@]} controller(s):"
for ev in "${pads[@]}"; do echo "  $(pad_name "$ev")"; done
if [[ ${#pads[@]} -lt $players ]]; then
  echo "Only ${#pads[@]} for $players players; the rest will start without a controller."
  players=${#pads[@]}
fi

conf=("# Generated by assign-controllers.sh: <player>=<uniq>|<phys>")
free=("${pads[@]}")
for ((p = 1; p <= players; p++)); do
  echo
  echo "Player $p: press a button on your controller..."
  ev=$(wait_for_button "${free[@]}")
  echo "  -> $(pad_name "$ev")"
  conf+=("# P$p: $(pad_name "$ev")" "$p=$(pad_id "$ev")")
  for i in "${!free[@]}"; do
    if [[ "${free[$i]}" == "$ev" ]]; then unset 'free[i]'; fi
  done
  free=("${free[@]}")
done

mkdir -p "$SANDBOX_DIR"
printf '%s\n' "${conf[@]}" >"$CONTROLLERS_CONF"
echo
echo "Saved to $CONTROLLERS_CONF"
